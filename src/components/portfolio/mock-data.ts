export function buildDemoHistory(): PortfolioSnapshotPoint[] {
  const base = 24_00_000;
  return Array.from({ length: 30 }, (_, i) => {
    const t = new Date(Date.now() - (29 - i) * 86_400_000);
    const wobble = Math.sin(i / 4) * 18000 + i * 2200;
    const value = base + wobble;
    return {
      timestamp: t.toISOString(),
      portfolioValue: value,
      periodPnl: wobble - (i > 0 ? Math.sin((i - 1) / 4) * 18000 + (i - 1) * 2200 : 0),
      returnPct: ((value - base) / base) * 100,
      drawdownPct: Math.min(0, -Math.abs(Math.sin(i / 3)) * 2.4),
      bseExposure: value * 0.48,
      nseExposure: value * 0.42,
      selectedAccountValue: value * 0.55,
      benchmarkValue: 100 + i * 0.12,
      benchmarkReturnPct: i * 0.12,
      netExposure: value * 0.72,
    };
  });
}

